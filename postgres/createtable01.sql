CREATE TABLE TAIKHOAN (
    MaTK VARCHAR(50) PRIMARY KEY,

    MaNV VARCHAR(50) UNIQUE REFERENCES NHANVIEN(MaNV),

    Username VARCHAR(50) UNIQUE NOT NULL,
