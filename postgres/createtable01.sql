/* =========================================================
   15. TRIGGER TỰ ĐỘNG CẬP NHẬT UpdatedAt
   ========================================================= */

CREATE OR REPLACE FUNCTION fn_update_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.UpdatedAt = CURRENT_TIMESTAMP;
    RETURN NEW;
