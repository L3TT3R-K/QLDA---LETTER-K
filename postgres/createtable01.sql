    CHECK (VaiTro IN (
        'ADMIN',
        'QUANLY_CHINHANH',
        'NHANVIEN_BANHANG',
        'NHANVIEN_KHO',
        'KETOAN'
    )),

    CONSTRAINT CK_TAIKHOAN_TRANGTHAI
    CHECK (TrangThai IN (0, 1))
);


/* =========================================================
