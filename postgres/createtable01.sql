/* =========================================================
   12. SYNC OFFLINE
   ========================================================= */

CREATE TABLE SYNCLOG (
    SyncID VARCHAR(50) PRIMARY KEY,

    ThucThe VARCHAR(50),
    RecordID VARCHAR(50),

    TrangThai VARCHAR(20) DEFAULT 'PENDING',
    -- PENDING
    -- SUCCESS
    -- FAILED
    -- CONFLICT

    GhiChu TEXT,

    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT CK_SYNCLOG_TRANGTHAI
    CHECK (TrangThai IN ('PENDING', 'SUCCESS', 'FAILED', 'CONFLICT'))
);

CREATE TABLE CONFLICTLOG (
    ConflictID VARCHAR(50) PRIMARY KEY,

    ThucThe VARCHAR(50),
    RecordID VARCHAR(50),

    DataLocal JSONB,
    DataServer JSONB,

    TrangThai VARCHAR(20) DEFAULT 'UNRESOLVED',
    -- UNRESOLVED
    -- RESOLVED_LOCAL
    -- RESOLVED_SERVER
    -- RESOLVED_MANUAL

    GhiChu TEXT,

    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT CK_CONFLICTLOG_TRANGTHAI
    CHECK (
        TrangThai IN (
            'UNRESOLVED',
            'RESOLVED_LOCAL',
            'RESOLVED_SERVER',
            'RESOLVED_MANUAL'
        )
    )
);


